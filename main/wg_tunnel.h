#pragma once

#include <stdbool.h>
#include <stdint.h>
#include "wg_config.h"

/*
 * wg_tunnel.h — жизненный цикл WireGuard-туннеля.
 *
 * Модуль запускает фоновую задачу-супервайзер, которая:
 *   1. ждёт подключения к WiFi и корректного времени (WireGuard использует
 *      метку времени в рукопожатии; без SNTP или времени из браузера сервер
 *      отвергнет пакеты);
 *   2. создаёт туннель и добавляет в разрешённые адреса всю туннельную подсеть
 *      (иначе ответы получателям, кроме самого устройства, не пройдут);
 *   3. следит за рукопожатием: если туннель не поднялся за WG_RECONNECT_AFTER_S —
 *      пересоздаёт его.
 *
 * В отличие от отдельного проекта WireGuard, здесь НЕТ перезагрузки «туннеля давно
 * нет»: устройство управляет зарядкой, и недоступный VPN-сервер не должен приводить
 * к периодическим перезагрузкам. Туннель просто пересоздаётся.
 *
 * Конфигурация «на пробу»: если в NVS есть кандидат (см. wg_config.h), туннель
 * запускается с ним. Нет рукопожатия за WG_TRIAL_TIMEOUT_S → кандидат удаляется
 * и устройство перезагружается со старой конфигурацией. Есть рукопожатие →
 * кандидат становится основным.
 *
 * Туннель НЕ становится сетевым интерфейсом по умолчанию: весь прочий трафик
 * (включая сами пакеты WireGuard до сервера) идёт через WiFi. HTTP-сервер слушает
 * все интерфейсы, поэтому веб-интерфейс доступен и по адресу устройства в туннеле.
 *
 * Время для рукопожатия берётся из системных часов; SNTP запускает stats.c,
 * либо время приходит из браузера (POST /api/time).
 */

#define WG_RECONNECT_AFTER_S   90      /* нет рукопожатия столько секунд → пересоздать туннель */
#define WG_TRIAL_TIMEOUT_S     120     /* время на проверку кандидата до отката */
#define WG_MIN_VALID_EPOCH     1700000000   /* время раньше этого считается неустановленным */

typedef enum {
    WG_STATE_DISABLED,       /* туннель не настроен */
    WG_STATE_WAIT_WIFI,      /* ждём подключения к WiFi */
    WG_STATE_WAIT_TIME,      /* ждём установки времени (SNTP) */
    WG_STATE_CONNECTING,     /* туннель создан, рукопожатия ещё нет */
    WG_STATE_UP,             /* рукопожатие есть, туннель работает */
} wg_state_t;

typedef struct {
    wg_state_t state;
    bool       trial;              /* работаем с конфигурацией-кандидатом */
    bool       clock_ok;           /* время установлено */
    int32_t    handshake_age_s;    /* секунд с последнего рукопожатия; -1 если не было */
} wg_status_t;

/**
 * Выбрать активную конфигурацию (кандидат или основная) и запустить
 * задачу-супервайзер. Вызывать после wifi_manager_init() и stats_init() (SNTP).
 */
void wg_tunnel_start(void);

/** Снимок состояния для страницы «Статус». */
void wg_tunnel_get_status(wg_status_t *out);

/** Читаемое имя состояния (для страницы «Статус» и логов). */
const char *wg_state_name(wg_state_t state);

/** Конфигурация, с которой туннель работает прямо сейчас (может быть кандидатом). */
const wg_config_t *wg_tunnel_active_config(void);

/** true, если системное время установлено (SNTP или браузер). */
bool wg_clock_is_valid(void);
