#pragma once

/*
 * charge_ctrl.h — управление зарядкой аккумулятора LiFePO4 через GPIO.
 *
 * Логика (START / STOP описана в config.h):
 *   - Зарядка начинается при выполнении любого условия START
 *   - Зарядка заканчивается при выполнении любого условия STOP
 *   - Прерванная зарядка (пропало питание) возобновляется при следующем включении,
 *     пока не достигнуто условие STOP
 *
 * Состояние зарядки сохраняется в NVS (ключ "in_progress" в пространстве "charge"),
 * поэтому даже после перезагрузки незавершённый цикл будет продолжен.
 */

typedef enum {
    CHARGE_STATE_IDLE,     /* зарядник выключен, ожидаем условие START */
    CHARGE_STATE_CHARGING, /* зарядник включён */
} charge_state_t;

/**
 * Инициализировать контроллер зарядки.
 * Настраивает GPIO, проверяет NVS на наличие прерванного цикла,
 * запускает фоновую задачу мониторинга.
 * Должна вызываться после settings_init() и bms_ble_init().
 */
void charge_ctrl_init(void);

/**
 * Получить текущее состояние зарядника.
 * Потокобезопасно.
 */
charge_state_t charge_ctrl_get_state(void);

/**
 * Применить новые GPIO-настройки зарядника немедленно.
 * Освобождает старый пин (переводит в вход), настраивает новый как выход,
 * переприменяет текущее состояние зарядки.
 */
void charge_ctrl_apply_gpio_settings(void);

/**
 * Разбудить задачу зарядки досрочно после изменения настроек.
 * Настройки применяются немедленно, не ждя следующего интервала (5 с).
 */
void charge_ctrl_notify_settings_changed(void);

/**
 * Ручное управление зарядником.
 * enable=true  → принудительно включить (сохраняется в NVS, переживёт перезагрузку).
 * enable=false → принудительно выключить (сохраняется в NVS).
 */
void charge_ctrl_set_override(bool enable);
